"""
Collect result CSVs into docs/data/results.js, which the website reads. Run after each experiment:

    python make_site_data.py

Uses the rotated-test-singer results (mean +- std over 5 folds):
    results/<model>_rotate_summary.csv   -> head "mean"  (mean pooling + logistic regression)
    results/<model>_attn_summary.csv     -> head "attn"  (attentive pooling head)
"""
import csv
import json
from pathlib import Path

# file prefix -> name shown on the website (order = order and colour on the page)
MODELS = {
    "wav2vec2-base": "wav2vec2-base",
    "wavlm-large": "WavLM-Large",
    "MERT-v1-95M": "MERT-95M",
}
HEADS = {"mean": "rotate", "attn": "attn"}

out = {}
for head, suffix in HEADS.items():
    out[head] = []
    for prefix, label in MODELS.items():
        f = Path("results") / f"{prefix}_{suffix}_summary.csv"
        if not f.exists():
            continue
        rows = []
        for r in csv.DictReader(open(f)):
            rows.append({
                "edit": r["edit"],
                "eer": round(float(r["eer_mean"]), 3), "eer_std": round(float(r["eer_std"]), 3),
                "accuracy": round(float(r["acc_mean"]), 3), "accuracy_std": round(float(r["acc_std"]), 3),
                "acc_real": round(float(r["acc_real_mean"]), 3), "acc_real_std": round(float(r["acc_real_std"]), 3),
                "acc_fake": round(float(r["acc_fake_mean"]), 3), "acc_fake_std": round(float(r["acc_fake_std"]), 3),
            })
        out[head].append({"model": label, "rows": rows})

dest = Path("docs/data/results.js")
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("// generated by make_site_data.py - do not edit by hand\nwindow.RESULTS = "
                + json.dumps(out, indent=1) + ";\n")
for head, models in out.items():
    print(f"{head}: " + (", ".join(m["model"] for m in models) or "(none yet)"))
print(f"wrote {dest}")
