"""
Collect the result CSVs written by baseline.py into docs/data/results.js,
which the website reads. Run after each new experiment:

    python make_site_data.py

Only the default full runs (n1000, seed 0) are picked up; change PATTERN if needed.
"""
import csv
import json
from pathlib import Path

PATTERN = "*_results_n1000_s0.csv"

# file prefix -> name shown on the website (order = order on the page)
MODELS = {
    "wav2vec2-base": "wav2vec2-base",
    "wavlm-large": "WavLM-Large",
    "MERT-v1-95M": "MERT-95M",
}

out = []
for prefix, label in MODELS.items():
    for f in Path("results").glob(PATTERN):
        if f.name.startswith(prefix + "_"):
            rows = list(csv.DictReader(open(f)))
            out.append({
                "model": label,
                "rows": [{k: (v if k == "edit" else round(float(v), 3)) for k, v in r.items()} for r in rows],
            })

dest = Path("docs/data/results.js")
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("// generated by make_site_data.py - do not edit by hand\nwindow.RESULTS = "
                + json.dumps(out, indent=1) + ";\n")
print(f"wrote {dest}: " + ", ".join(m["model"] for m in out))
